from __future__ import annotations

import statistics
import sys
import time
from collections import Counter
from pathlib import Path

from backend.ingest import IngestError, parse_session
from backend.narrative import build_facts, configured_providers, generate_debrief
from backend.pipeline import load_config, session_problem
from backend.rules import pick_takeaway, run_rules
from backend.stats import compute_stats

CONTEXT = {"make": "BMW", "model": "M3 F80", "drivetrain": "RWD"}
PAUSE_S = 4


def main(folder: str, out: str, runs: int = 3) -> None:
    if not configured_providers():
        sys.exit("No LLM provider configured - add a key to .env first.")
    cfg = load_config()
    rows, latencies, issue_counts = [], [], Counter()
    first_try = final_llm = total = 0
    for path in sorted(Path(folder).glob("*.csv")):
        try:
            session = parse_session(path, path.name)
        except IngestError:
            continue
        if session_problem(session, cfg):
            continue
        st = compute_stats(session, cfg)
        flags = run_rules(st, cfg, CONTEXT)
        tk = pick_takeaway(flags)
        build_facts(st, flags, tk, CONTEXT)
        for run in range(1, runs + 1):
            t0 = time.perf_counter()
            out_n = generate_debrief(st, flags, tk, CONTEXT)
            dt = time.perf_counter() - t0
            total += 1
            latencies.append(dt)
            first = out_n["attempts"][0] if out_n["attempts"] else {}
            ok_first = not first.get("error") and not first.get("issues")
            first_try += ok_first
            final_llm += out_n["source"] == "llm"
            for a in out_n["attempts"]:
                for i in a.get("issues") or []:
                    issue_counts[i.split(" in the narrative")[0].split(":")[0]] += 1
                if a.get("error"):
                    issue_counts["Provider or format error: " + a["error"][:60]] += 1
            rows.append(f"| {path.name[:48]} | {run} | {'pass' if ok_first else 'fail'} | {out_n['source']} | "
                        f"{out_n['model'] or '-'} | {len(out_n['attempts'])} | {dt:.1f}s |")
            print(rows[-1], flush=True)
            time.sleep(PAUSE_S)
    p50 = statistics.median(latencies)
    p95 = sorted(latencies)[max(0, int(round(0.95 * len(latencies))) - 1)]
    text = [
        "# AI narrative faithfulness evaluation", "",
        f"Generated by `scripts/faithfulness_eval.py` on {time.strftime('%Y-%m-%d')} with providers "
        f"{', '.join(configured_providers())}; {runs} runs per usable real session.", "",
        "| Measure | Result |", "|---|---|",
        f"| Narratives generated | {total} |",
        f"| Passed the fact check on the first try | {first_try}/{total} ({100 * first_try / total:.0f}%) |",
        f"| Final report used an AI narrative | {final_llm}/{total} ({100 * final_llm / total:.0f}%) |",
        f"| Final report used the template fallback | {total - final_llm}/{total} |",
        f"| Narrative latency p50 / p95 | {p50:.1f}s / {p95:.1f}s |", "",
        "Every AI narrative shown to a user passed the check: no number outside the verified facts, the takeaway",
        "matches the rule engine's priority flag, no causal claim stronger than the flags make (\"due to\"),",
        "only known flags cited, all four tyres covered, no garbled text. A rejected draft is retried once with the reasons.", "",
        "## Rejection reasons", "",
        *([f"- {k}: {v}" for k, v in issue_counts.most_common()] or ["- none"]), "",
        "## Runs", "",
        "| Session | Run | First try | Final source | Model | Attempts | Time |", "|---|---|---|---|---|---|---|",
        *rows,
    ]
    Path(out).write_text("\n".join(text) + "\n", encoding="utf-8")
    print("\n".join(text[:12]))


if __name__ == "__main__":
    main(sys.argv[1], sys.argv[2], int(sys.argv[3]) if len(sys.argv) > 3 else 3)
