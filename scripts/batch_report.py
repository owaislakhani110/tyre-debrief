from __future__ import annotations

import sys
import time
from pathlib import Path

from backend.ingest import IngestError
from backend.pipeline import analyse, load_config
from backend.rules import _fmt_lap


def main(folder: str, out: str, use_llm: bool = False) -> None:
    cfg = load_config()
    rows, details = [], []
    paths = [p for f in folder.split(",") for p in sorted(Path(f).glob("*")) if p.suffix.lower() in (".csv", ".xrk", ".xrz")]
    for path in paths:
        t0 = time.perf_counter()
        try:
            r = analyse(path, path.name, {"make": "BMW", "model": "F80 M3", "drivetrain": "RWD"}, cfg, with_narrative=use_llm)
        except IngestError as exc:
            rows.append(f"| {path.name} | — | — | — | **Rejected:** {exc} | {time.perf_counter() - t0:.1f}s |")
            continue
        s, ls = r["stats"]["session"], r["stats"]["lap_summary"]
        top = next((f for f in r["flags"] if f["id"] == r["takeaway_flag_id"]), None)
        counts = {}
        for f in r["flags"]:
            counts[f["severity"]] = counts.get(f["severity"], 0) + 1
        rows.append(f"| {path.name} | {s['date'].split(', ', 1)[-1]} | {ls['valid']} | {_fmt_lap(ls['best_time_s'])} | "
                    f"{top['title'] if top else 'No actionable flag'} | {r['timings']['total_s']}s |")
        details.append(f"### {path.name}\n")
        details.append("| Severity | Rule | Finding |\n|---|---|---|")
        details += [f"| {f['severity']} | `{f['rule']}` | {f['title']} |" for f in r["flags"]]
        details.append("")
    text = ["# Session results (all real Winton sessions: CSV exports and XRK logger files)", "",
            "Generated by `scripts/batch_report.py` with the thresholds in `config/thresholds.yaml`.", "",
            "| File | Date | Valid laps | Best lap | Top-priority takeaway | Time |", "|---|---|---|---|---|---|",
            *rows, "", "## Flags per session", "", *details]
    Path(out).write_text("\n".join(text), encoding="utf-8")
    print("\n".join(rows))


if __name__ == "__main__":
    main(sys.argv[1], sys.argv[2], "--llm" in sys.argv)
